package update

import "crypto/ed25519"

// The release signing key is kept outside the repository. This fixed public
// key is identical to the SubjectPublicKeyInfo in public-key.pem.
var trustedPublicKey = [ed25519.PublicKeySize]byte{0x12, 0x77, 0x6e, 0xcf, 0xef, 0x8c, 0xfe, 0x6e, 0xfb, 0x0a, 0x2c, 0xe6, 0x74, 0xa1, 0xcf, 0xfc, 0x9c, 0xdb, 0x87, 0xc0, 0x85, 0x31, 0x12, 0x50, 0x14, 0xdf, 0xa3, 0x1a, 0xb4, 0xea, 0x06, 0x33}

func TrustedPublicKey() (ed25519.PublicKey, error) {
	key := make(ed25519.PublicKey, ed25519.PublicKeySize)
	copy(key, trustedPublicKey[:])
	return key, nil
}
